"""
Scope table of a set of audience records, in the contract `onomasia:scope-table@1`.

The scope table states the ancestors and the descendants of each audience, as the decision on
audiences states. The ancestors of an audience are the transitive closure of its parents, and its
descendants are the transitive closure of the inverse relation. Onomasia reads the table to decide
which lexical rules bind a text, so a table that differs from the one derived from the records is
reported as stale.

The table is written deterministically: its audiences are sorted by identifier, and the ancestors
and the descendants of each audience are sorted. The common field `sources` names the repository
holding the root, with its commit checked out and whether the records read held uncommitted
changes, so it changes with every commit. The comparison of a table with the derived one therefore
checks the structure of `sources` and leaves its values aside; it compares the contract and the
rows, each row as sets of ancestors and of descendants.

Classes
-------
Row
    Ancestors and descendants of one audience.
ScopeTable
    The row of each audience of a set of audience records.

Attributes
----------
SCOPE_TABLE_CONTRACT : str
    The contract of the scope table, published by Onomasia.
SCOPE_TABLE_CURRENT : Rule
    The rule that a scope table equals the table derived from the audience records.
"""

import re
from collections.abc import Iterable, Iterator, Mapping, Sequence
from dataclasses import dataclass, replace
from pathlib import Path

import yaml

from .audiences import Audience, closure
from .findings import Finding, Rule, Severity
from .layout import FieldPath
from .positions import parse, position
from .provenance import Source

SCOPE_TABLE_CONTRACT = "onomasia:scope-table@1"

SCOPE_TABLE_CURRENT = Rule(
    "scope-table-current",
    "The scope table equals the table derived from the parents of the audience records.",
    Severity.ERROR,
)

HEADER = "# Generated by `ekthesis scope-table` from the audience records; do not edit by hand.\n"
"""Comment opening a written table."""

CONTRACT_FIELD = "contract"
SOURCES_FIELD = "sources"
AUDIENCES_FIELD = "audiences"
TABLE_FIELDS = (CONTRACT_FIELD, SOURCES_FIELD, AUDIENCES_FIELD)
SOURCE_FIELDS = ("repository", "commit", "dirty")
ROW_FIELDS = ("ancestors", "descendants")
COMMIT = re.compile(r"[0-9a-f]{40}\Z")
"""Full identifier of a commit, as the common field `sources` of Onomasia writes it."""


@dataclass(frozen=True)
class Row:
    """
    Ancestors and descendants of one audience, each sorted by identifier.

    Attributes
    ----------
    ancestors : tuple of str
        The audiences reached from the audience through its parents, in one or more steps.
    descendants : tuple of str
        The audiences whose ancestors hold the audience.
    """

    ancestors: tuple[str, ...]
    descendants: tuple[str, ...]

    def to_data(self) -> dict[str, list[str]]:
        """Return the row as it is written in the table."""
        return {"ancestors": list(self.ancestors), "descendants": list(self.descendants)}


@dataclass(frozen=True)
class ScopeTable:
    """
    The row of each audience of a set of audience records.

    Attributes
    ----------
    rows : Mapping of str to Row
        Row of each audience, by identifier, in the order of the identifiers.
    """

    rows: Mapping[str, Row]

    @classmethod
    def derive(cls, audiences: Iterable[Audience]) -> "ScopeTable":
        """
        Derive the table of `audiences`, whose identifiers are distinct and whose parents form
        no cycle.

        Parameters
        ----------
        audiences : Iterable of Audience
            Audience records, each of whose parents is among them.

        Returns
        -------
        ScopeTable
            The row of each audience, with its ancestors and its descendants.
        """
        parents = {
            audience.identifier: [name for _, name in audience.parents] for audience in audiences
        }
        children: dict[str, list[str]] = {identifier: [] for identifier in parents}
        for child, names in parents.items():
            for parent in names:
                children.setdefault(parent, []).append(child)
        ancestors = closure(parents)
        descendants = closure(children)
        return cls(
            {
                identifier: Row(
                    tuple(sorted(ancestors[identifier])), tuple(sorted(descendants[identifier]))
                )
                for identifier in sorted(parents)
            }
        )

    def document(self, sources: Sequence[Source]) -> dict[str, object]:
        """Return the table as a document of `onomasia:scope-table@1`, naming `sources`."""
        return {
            CONTRACT_FIELD: SCOPE_TABLE_CONTRACT,
            SOURCES_FIELD: [source.to_data() for source in sources],
            AUDIENCES_FIELD: {identifier: row.to_data() for identifier, row in self.rows.items()},
        }

    def text(self, sources: Sequence[Source]) -> str:
        """Return the YAML text of the table, naming `sources`, as it is written to a file."""
        body = yaml.safe_dump(
            self.document(sources), sort_keys=False, allow_unicode=True, default_flow_style=False
        )
        return HEADER + body

    def differences(self, path: Path) -> list[Finding]:
        """
        Return a finding for each difference between the table at `path` and this table.

        The table must hold exactly the fields `contract`, `sources` and `audiences`, and each item
        of `sources` exactly a text `repository`, a full commit `commit` and a boolean `dirty`,
        whose values are not compared. A row that the derived table lacks, holds alone, or holds
        with other ancestors or descendants, in any order, yields one finding located at that row.
        """
        try:
            data, node = parse(path)
        except FileNotFoundError:
            return [_finding(path, FieldPath(), "the scope table does not exist")]
        except (OSError, UnicodeDecodeError, yaml.YAMLError) as error:
            return [_finding(path, FieldPath(), f"cannot read the scope table: {error}")]
        return [
            replace(finding, position=position(node, finding.locus()))
            for finding in self._compare(path, data)
        ]

    def _compare(self, path: Path, data: object) -> Iterator[Finding]:
        """Yield the differences between the table `data` read from `path` and this table."""
        if not isinstance(data, Mapping):
            yield _finding(path, FieldPath(), "the scope table holds no mapping")
            return
        yield from _fields(path, FieldPath(), data, TABLE_FIELDS, "the scope table")
        if CONTRACT_FIELD in data and data[CONTRACT_FIELD] != SCOPE_TABLE_CONTRACT:
            yield _finding(
                path,
                FieldPath((CONTRACT_FIELD,)),
                f"the scope table names the contract {data[CONTRACT_FIELD]}, "
                f"not {SCOPE_TABLE_CONTRACT}",
            )
        if SOURCES_FIELD in data:
            yield from _sources(path, data[SOURCES_FIELD])
        if AUDIENCES_FIELD in data:
            yield from self._rows(path, data[AUDIENCES_FIELD])

    def _rows(self, path: Path, rows: object) -> Iterator[Finding]:
        """Yield the differences between the rows `rows` of the table and the derived rows."""
        at = FieldPath((AUDIENCES_FIELD,))
        if not isinstance(rows, Mapping):
            yield _finding(path, at, "the audiences of the scope table form no mapping")
            return
        written = {str(identifier): row for identifier, row in rows.items()}
        for identifier in sorted(written.keys() | self.rows.keys()):
            derived = self.rows.get(identifier)
            if derived is None:
                yield _finding(
                    path,
                    at.child(identifier),
                    f"the row of {identifier} names no audience record",
                )
            elif identifier not in written:
                yield _finding(
                    path,
                    at,
                    f"the row of {identifier} is missing",
                    absent=identifier,
                )
            elif not _same_row(written[identifier], derived):
                yield _finding(
                    path,
                    at.child(identifier),
                    f"the row of {identifier} differs from the derived row: ancestors "
                    f"{list(derived.ancestors)}, descendants {list(derived.descendants)}",
                )


def _fields(
    path: Path, at: FieldPath, data: Mapping[object, object], fields: tuple[str, ...], name: str
) -> Iterator[Finding]:
    """Yield a finding for each field of `fields` that `data` lacks, and for each other field."""
    for missing in fields:
        if missing not in data:
            yield _finding(path, at, f"{name} lacks the field {missing}", absent=missing)
    for key in data:
        if key not in fields:
            yield _finding(
                path, at.child(str(key)), f"{name} holds the field {key}, which its contract omits"
            )


def _sources(path: Path, sources: object) -> Iterator[Finding]:
    """Yield a finding for each defect of the structure of the field `sources`."""
    at = FieldPath((SOURCES_FIELD,))
    if not isinstance(sources, list):
        yield _finding(path, at, "the sources of the scope table form no list")
        return
    for index, source in enumerate(sources):
        item = at.child(index)
        if not isinstance(source, Mapping):
            yield _finding(path, item, f"the source {index} of the scope table is no mapping")
            continue
        yield from _fields(path, item, source, SOURCE_FIELDS, f"the source {index}")
        for key in SOURCE_FIELDS:
            expected = _source_defect(key, source.get(key)) if key in source else None
            if expected is not None:
                yield _finding(
                    path, item.child(key), f"the {key} of the source {index} is {expected}"
                )


def _source_defect(key: str, value: object) -> str | None:
    """State what the value `value` of the field `key` of a source fails to be, or `None`."""
    if key == "repository" and not (isinstance(value, str) and value):
        return "no text"
    if key == "commit" and not (isinstance(value, str) and COMMIT.match(value)):
        return "no full commit of 40 hexadecimal digits"
    if key == "dirty" and not isinstance(value, bool):
        return "no boolean"
    return None


def _same_row(written: object, derived: Row) -> bool:
    """Whether the row `written` holds exactly the ancestors and the descendants of `derived`."""
    if not isinstance(written, Mapping) or set(written) != set(ROW_FIELDS):
        return False
    for key, expected in zip(ROW_FIELDS, (derived.ancestors, derived.descendants)):
        values = written[key]
        if not isinstance(values, list) or not all(isinstance(value, str) for value in values):
            return False
        if sorted(values) != list(expected):
            return False
    return True


def _finding(path: Path, field: FieldPath, message: str, absent: str | None = None) -> Finding:
    """Build a finding of `scope-table-current` on the table at `path`."""
    rule = SCOPE_TABLE_CURRENT
    return Finding(rule.identifier, path, field, rule.severity, message, absent=absent)
